// Performance HQ end-to-end tests — team testing: teams and rosters, test days, entry by athlete and by test, results, CSV, editing
// Run all suites with:  npm test   (see CLAUDE.md)
const { chromium, devices } = require('playwright');
const fs = require('fs');
const SP = process.env.OUT_DIR || '.', BASE = (process.env.BASE_URL || 'http://localhost:8080/');
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('  ✓ ' + m); };
const near = (a, b, t = 0.005) => Math.abs(a - b) <= t;
(async () => {
  const browser = await chromium.launch();
  const errors = [];
  const ctx = await browser.newContext({ ...devices['iPhone 13'], acceptDownloads: true });
  const p = await ctx.newPage();
  p.on('pageerror', e => errors.push(e.message));
  p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const top = () => '.modal-wrap >> nth=-1';
  const submit = () => p.click(`${top()} >> .modal-head button[type=submit]`);
  const st = (fn, a) => p.evaluate(fn, a);
  const fits = async () => (await st(() => document.documentElement.scrollWidth)) <= 391;
  const blur = () => p.evaluate(() => document.activeElement?.blur());
  const dlgOk = () => p.click('.dialog .dlg-actions button >> nth=0');
  await p.goto(BASE); await p.waitForSelector('.modal'); await p.check('input[name=demo]'); await submit(); await p.waitForTimeout(700);
  const id = name => st(n => S.athletes.find(a => athleteName(a) === n)?.id, name);
  const maya = await id('Maya Thompson'), ava = await id('Ava Chen');

  console.log('== Teams page and roster');
  await p.goto(BASE + '#/teams'); await p.waitForTimeout(250);
  let view = await p.innerText('#view');
  assert(view.includes('No teams yet') && view.includes('Make teams from your athletes') && view.includes('Westfield HS'), 'empty state, with teams suggested from the Team / school field');
  assert(await p.locator('.sidebar [data-nav=teams]').count() === 1, 'Team Testing has its own section in the menu');
  assert(await fits(), 'teams page fits the iPhone screen');
  await p.click('.top-actions [data-act=ttTeam]'); await p.waitForTimeout(200);
  await p.fill(`${top()} >> [name=name]`, 'Hunterdon Central');
  await p.fill(`${top()} >> [name=sport]`, 'Soccer');
  await p.click(`${top()} >> .picker-list label:has-text("Maya Thompson")`);
  await p.click(`${top()} >> .picker-list label:has-text("Ava Chen")`);
  await p.fill(`${top()} >> [name=newAth]`, 'Jane Smith, F, 4/12/2010\nMike\tJones\tM\t2009-08-30\nAva Chen\nBad Date, 13/45/2010');
  await p.waitForTimeout(100);
  const pv = await p.innerText('#ttNewPrev');
  assert(pv.includes('Jane Smith') && pv.includes('Mike Jones') && pv.includes('Already in GSP HQ') && pv.includes('not recognised'), `roster paste preview: new, existing and errors (“${pv.replace(/\n/g, ' | ')}”)`);
  await submit(); await p.waitForTimeout(150);
  assert((await p.innerText(`${top()} >> .form-error`)).includes('Bad Date'), 'bad birth date blocks saving');
  await p.fill(`${top()} >> [name=newAth]`, 'Jane Smith, F, 4/12/2010\nMike\tJones\tM\t2009-08-30\nAva Chen');
  await submit(); await p.waitForTimeout(400);
  const team = await st(() => S.teams[0]);
  const jane = await id('Jane Smith'), mike = await id('Mike Jones');
  const nj = await st(i => getAthlete(i), jane), nm = await st(i => getAthlete(i), mike);
  assert(team && team.name === 'Hunterdon Central' && team.athleteIds.length === 4 && [maya, ava, jane, mike].every(x => team.athleteIds.includes(x)), 'team created with 2 existing + 2 new athletes (no duplicate Ava)');
  assert(nj.sex === 'F' && nj.dob === '2010-04-12' && nj.sport === 'Soccer' && nj.team === 'Hunterdon Central' && nm.sex === 'M' && nm.dob === '2009-08-30' && nm.lastName === 'Jones', 'new athletes get sex, birth date (4/12/2010 and ISO), sport and team; spreadsheet columns read');
  assert(p.url().includes('#/teams/' + team.id) && (await p.innerText('#view')).includes('Roster'), 'opens the team page');
  assert(await fits(), 'team page fits the iPhone screen');

  console.log('== Start a test day');
  await p.click('.top-actions [data-act=ttStart]'); await p.waitForTimeout(250);
  assert(await p.locator(`${top()} >> .picker-list input:checked`).count() === 4, 'whole team is selected');
  await p.click(`${top()} >> [data-ttp="0"]`); await p.waitForTimeout(80);
  await p.click(`${top()} >> #ttChips [data-ttk=cmj]`); await p.waitForTimeout(80);
  assert(await p.locator(`${top()} >> .tt-selrow`).count() === 4, 'speed & agility quick pick + CMJ = 4 tests');
  assert((await p.inputValue(`${top()} >> [data-tts=cmj]`)) === 'avg' && (await p.inputValue(`${top()} >> [data-ttn=cmj]`)) === '3' && (await p.inputValue(`${top()} >> [data-tts=sprint10yd]`)) === 'best' && (await p.inputValue(`${top()} >> [data-ttn=sprint10yd]`)) === '2', 'defaults: speed best of 2, CMJ average of 3 (same as the evaluation)');
  await p.selectOption(`${top()} >> [data-ttn=fly10yd]`, '3');
  assert(await fits(), 'setup form fits the iPhone screen');
  await p.screenshot({ path: SP + '/v19-team-setup.png', fullPage: true });
  await submit(); await p.waitForTimeout(400);
  const sess = await st(() => S.teamtests[0]);
  assert(sess && sess.teamId === team.id && JSON.stringify(sess.keys) === '["sprint10yd","fly10yd","proAgility","cmj"]' && sess.n.fly10yd === 3 && sess.athleteIds.length === 4 && p.url().includes('#/teamtest/' + sess.id), 'test day saved and opened');
  assert(await st(id => S.teams.find(t => t.id === id).keys.length === 4, team.id), 'team remembers its tests for next time');

  console.log('== By athlete');
  assert((await p.innerText('.tt-ath h2')) === 'Ava Chen' && await p.locator('#ttRoot [data-tt$="|fly10yd"]').count() === 3, 'first athlete (A–Z) with a box per trial');
  const fill = async (aid, k, vals) => { for (let i = 0; i < vals.length; i++) await p.fill(`#ttRoot [data-tt="${aid}|${k}"][data-i="${i}"]`, String(vals[i])); };
  await fill(ava, 'sprint10yd', ['1.80', '12.4']); await fill(ava, 'fly10yd', ['1.40', '1.38', '1.45']); await fill(ava, 'proAgility', ['5.1', '5.0']); await fill(ava, 'cmj', [15, 16, 17]);
  assert(await p.locator('#ttRoot [data-ttbm]').count() === 0, 'no body-mass box when no test needs it');
  await blur(); await p.waitForTimeout(400);
  const fb = await p.innerText(`[data-fb="${ava}|sprint10yd"]`);
  assert(fb.includes('Best 1.65 s') && fb.includes('12.4 mph'), `MPH read from the timer, fastest trial shown (“${fb}”)`);
  let rec = await st(([s, a]) => S.tests.find(t => t.teamTestId === s && t.athleteId === a), [sess.id, ava]);
  assert(rec && near(rec.m.sprint10yd, 1.65) && rec.m.fly10yd === 1.38 && rec.trials.fly10yd.length === 3 && rec.m.proAgility === 5 && near(rec.m.cmj, 40.64, 0.01) && rec.bodyMassKg > 0 && rec.notes.includes('Hunterdon Central'), 'saved to Ava’s own test record: best times, CMJ average, last known body mass, linked to the test day');
  assert((await p.innerText('#ttHead')).includes('1 of 4 done') && (await p.innerText('#ttSt')) === 'Done', 'progress and status update as you go');
  assert((await p.innerText(`[data-fb="${ava}|cmj"]`)).includes('vs last'), 'compares with the athlete’s last result');
  assert(await fits(), 'athlete entry fits the iPhone screen');
  await p.screenshot({ path: SP + '/v19-team-athlete.png', fullPage: true });
  await p.click('.tt-foot [data-act=ttGo]'); await p.waitForTimeout(300);
  assert((await p.innerText('.tt-ath h2')) === 'Jane Smith', 'Next goes to the next athlete');
  await fill(jane, 'sprint10yd', ['1.68']); await blur(); await p.waitForTimeout(250);
  assert((await p.innerText('#ttSt')) === 'Partly done', 'partly tested athletes are marked');

  console.log('== By test (station)');
  await p.click('.tt-tabs a:has-text("By test")'); await p.waitForTimeout(300);
  assert(await p.locator('#ttRoot .tt-row').count() === 4 && (await p.innerText('.tt-keys')).includes('2/4'), 'whole team listed for the first test, with how many are done');
  await fill(maya, 'sprint10yd', ['1.70', '1.72']);
  await fill(mike, 'sprint10yd', ['16.5']); await p.waitForTimeout(100);
  const warn = await p.innerText(`[data-fb="${mike}|sprint10yd"]`);
  assert(warn.includes('faster than the team’s middle result') && warn.includes('Double-check'), `typo guard on a result far from the team (“${warn.replace(/\n/g, ' ')}”)`);
  await p.fill(`#ttRoot [data-tt="${mike}|sprint10yd"][data-i="1"]`, 'abc'); await p.waitForTimeout(80);
  assert(await p.locator(`#ttRoot [data-tt="${mike}|sprint10yd"][data-i="1"].bad`).count() === 1 && (await p.innerText(`[data-fb="${mike}|sprint10yd"]`)).includes('Enter seconds'), 'invalid entry is flagged');
  await p.fill(`#ttRoot [data-tt="${mike}|sprint10yd"][data-i="0"]`, '1.75');
  await p.fill(`#ttRoot [data-tt="${mike}|sprint10yd"][data-i="1"]`, '1.77');
  // leave without tapping elsewhere: the typed value must still be saved
  await st(() => { location.hash = location.hash.replace('v=test', 'v=results'); }); await p.waitForTimeout(400);
  const mk = await st(([s, a]) => S.tests.find(t => t.teamTestId === s && t.athleteId === a)?.m, [sess.id, mike]);
  assert(mk && mk.sprint10yd === 1.75, 'values typed but not confirmed are saved when leaving the page');
  await p.goto(BASE + `#/teamtest/${sess.id}?v=test&k=sprint10yd`); await p.waitForTimeout(300);
  assert(await fits(), 'station entry fits the iPhone screen');
  await p.screenshot({ path: SP + '/v19-team-station.png', fullPage: true });

  console.log('== Absent');
  await p.goto(BASE + `#/teamtest/${sess.id}?v=athlete&a=${jane}`); await p.waitForTimeout(300);
  await p.click('.tt-foot [data-act=ttAbsent]'); await p.waitForTimeout(200);
  await dlgOk(); await p.waitForTimeout(300);
  const ab = await st(([s, a]) => ({ abs: S.teamtests.find(x => x.id === s).absentIds, rec: S.tests.some(t => t.teamTestId === s && t.athleteId === a) }), [sess.id, jane]);
  assert(ab.abs.includes(jane) && !ab.rec && (await p.innerText('#ttHead')).includes('1 absent'), 'absent: confirmed, her results removed, counted separately');

  console.log('== Results');
  await p.click('.tt-tabs a:has-text("Results")'); await p.waitForTimeout(300);
  view = await p.innerText('#view');
  const first = await p.locator('.tt-grid .card').first().innerText();
  assert(first.includes('0–10 yd') || first.includes('10 yd sprint'), 'a ranking card per test');
  assert(first.indexOf('Ava Chen') < first.indexOf('Maya Thompson') && first.indexOf('Maya Thompson') < first.indexOf('Mike Jones'), 'ranked fastest first (Ava 1.65, Maya 1.70, Mike 1.75)');
  assert(first.includes('Team average') && first.includes('1.70 s'), 'team average shown');
  assert(view.includes('All results') && view.includes('Absent') && view.toLowerCase().includes('still to test'), 'full table, absent athletes and who is left to test');
  assert(await fits(), 'results fit the iPhone screen');
  await p.screenshot({ path: SP + '/v19-team-results.png', fullPage: true });
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('.tt-foot [data-act=ttCsv]')]);
  const csv = fs.readFileSync(await dl.path(), 'utf8');
  const avaLine = csv.split('\n').find(l => l.startsWith('Ava Chen'));
  assert(dl.suggestedFilename().startsWith('team-test-hunterdon-central-') && csv.includes('0–10 yd (s) best') && csv.includes('5 yd build + 10 yd fly (s) best') && csv.includes('trial 3') && avaLine.includes('1.65') && avaLine.includes('1.38') && avaLine.includes('Done') && csv.includes('Jane Smith,F,'), 'CSV export with scores, every trial and status');
  await p.click('.tt-foot [data-act=ttFinish]'); await p.waitForTimeout(250);
  assert(await st(s => S.teamtests.find(x => x.id === s).done, sess.id) && (await p.innerText('#ttHead')).includes('Finished'), 'test day can be finished');

  console.log('== Profile, leaderboard and percentiles see the results');
  await p.goto(BASE + `#/athlete/${ava}`); await p.waitForTimeout(250);
  assert((await p.innerText('.profile-head')).includes('Hunterdon Central'), 'athlete profile links to the team');
  assert(await st(a => metricSeries(a, 'sprint10yd').length === 1 && lbEntries('sprint10yd').some(e => e.aid === a), ava), 'team results are normal test results (charts, leaderboard, percentiles)');

  console.log('== Editing a test day');
  await p.goto(BASE + `#/teamtest/${sess.id}?v=results`); await p.waitForTimeout(250);
  await p.click('.top-actions [data-act=ttEdit]'); await p.waitForTimeout(250);
  const old = await st(() => addDays(today(), -14));
  await p.fill(`${top()} >> [name=date]`, old);
  await p.click(`${top()} >> #ttSel [data-ttk=cmj]`); await p.waitForTimeout(60);
  await p.selectOption(`${top()} >> [data-tts=fly10yd]`, 'avg');
  await submit(); await p.waitForTimeout(250);
  assert((await p.innerText('.dialog')).includes('Results for CMJ height will be deleted'), 'removing a test with results asks first');
  await dlgOk(); await p.waitForTimeout(400);
  rec = await st(([s, a]) => S.tests.find(t => t.teamTestId === s && t.athleteId === a), [sess.id, ava]);
  assert(rec.date === old && rec.m.cmj === undefined && near(rec.m.fly10yd, (1.40 + 1.38 + 1.45) / 3, 1e-9) && near(rec.m.sprint10yd, 1.65), 'date moves every result, removed test deleted, fly re-scored as the average');

  console.log('== Second test day: personal bests and team change');
  await p.goto(BASE + `#/teams/${team.id}`); await p.waitForTimeout(250);
  await p.click('.top-actions [data-act=ttStart]'); await p.waitForTimeout(250);
  assert(await p.locator(`${top()} >> .tt-selrow`).count() === 3, 'the team’s last tests are pre-selected');
  await submit(); await p.waitForTimeout(400);
  const s2 = await st(() => S.teamtests.find(x => x.date === today() && !x.done));
  await p.goto(BASE + `#/teamtest/${s2.id}?v=test&k=sprint10yd`); await p.waitForTimeout(300);
  await fill(ava, 'sprint10yd', ['1.60']); await fill(maya, 'sprint10yd', ['1.74']); await blur(); await p.waitForTimeout(300);
  assert((await p.innerText(`[data-fb="${ava}|sprint10yd"]`)).includes('New PB'), 'new personal best flagged while entering');
  await p.click('.tt-tabs a:has-text("Results")'); await p.waitForTimeout(300);
  view = await p.innerText('#view');
  assert(view.toLowerCase().includes('new personal bests') && view.includes('since') && view.includes('avg of 2 athletes'), 'results: PBs and team change vs the last test day (same athletes)');
  await p.goto(BASE + `#/teams/${team.id}`); await p.waitForTimeout(250);
  view = await p.innerText('#view');
  assert(view.includes('Team progress') && view.includes('In progress') && view.includes('Finished'), 'team page: test days and team progress');

  console.log('== Sync, validation and clean-up');
  const v = await st(() => {
    const c = normalizeState({ teams: [{ id: 't9', name: 'X'.repeat(200), athleteIds: ['ok1', 'bad id!'], keys: ['cmj', '<x>'], n: { cmj: 9, vj: 2 }, score: { cmj: 'max', vj: 'best' } }], teamtests: [{ id: 's9', date: 'nope', athleteIds: 'x', absentIds: ['a1'], done: 'yes', keys: ['sprint10yd'] }] });
    const r = mergeState(c);
    return { t: c.teams[0], s: c.teamtests[0], added: r.added, has: S.teams.some(t => t.id === 't9') };
  });
  assert(v.t.name.length === 120 && JSON.stringify(v.t.athleteIds) === '["ok1"]' && JSON.stringify(v.t.keys) === '["cmj"]' && JSON.stringify(v.t.n) === '{"vj":2}' && JSON.stringify(v.t.score) === '{"vj":"best"}', 'teams validated on load / import / sync');
  assert(Array.isArray(v.s.athleteIds) && v.s.athleteIds.length === 0 && v.s.done === false && /^\d{4}-\d{2}-\d{2}$/.test(v.s.date) && v.added === 2 && v.has, 'test days validated, and new collections merge through sync');
  const mi = await st(() => [metricIn({ kind: 'mass' }, 220), metricIn({ kind: 'len' }, 10), metricIn({ unit: 's' }, 1.5)]);
  assert(near(mi[0], 99.79, 0.01) && near(mi[1], 25.4, 1e-9) && mi[2] === 1.5, 'typed weights in custom tests are converted to kg (fix)');
  await p.goto(BASE + `#/teamtest/${s2.id}?v=results`); await p.waitForTimeout(250);
  await p.click('.top-actions [data-act=ttEdit]'); await p.waitForTimeout(200);
  await p.click(`${top()} >> [data-del]`); await p.waitForTimeout(200); await dlgOk(); await p.waitForTimeout(400);
  assert(await st(s => !S.teamtests.some(x => x.id === s) && !S.tests.some(t => t.teamTestId === s), s2.id), 'deleting a test day removes its results');
  await p.goto(BASE + `#/teams/${team.id}`); await p.waitForTimeout(250);
  await p.click('.top-actions [data-act=ttTeam]'); await p.waitForTimeout(200);
  await p.click(`${top()} >> [data-del]`); await p.waitForTimeout(200); await dlgOk(); await p.waitForTimeout(400);
  assert(await st(([t, a, s]) => !S.teams.some(x => x.id === t) && !!getAthlete(a) && S.tests.some(x => x.teamTestId === s), [team.id, jane, sess.id]), 'deleting a team keeps the athletes and their results');
  await p.goto(BASE + '#/teams'); await p.waitForTimeout(250);
  assert((await p.innerText('#view')).includes('Hunterdon Central'), 'past test day still listed under its team name');

  await browser.close();
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'ALL PASSED, NO CONSOLE ERRORS');
})().catch(e => { console.error(e.message); process.exit(1); });
